// Helper to construct nodes cleanly
function createNode(params: Partial<SpatialNode> & { id: string; type: SpatialNode["type"]; label: string; x: number; y: number }): SpatialNode {
  return {
    id: params.id,
    type: params.type,
    label: params.label,
    sublabel: params.sublabel || params.type.toUpperCase(),
    x: params.x,
    y: params.y,
    status: params.status || "completed",
    durationMs: params.durationMs || 10,
    timestamp: params.timestamp || new Date().toISOString(),
    spanId: params.spanId || `span-${params.id}`,
    parentSpanId: params.parentSpanId || null,
    agentId: params.agentId,
    modelId: params.modelId,
    identity: {
      nodeId: params.id,
      nodeType: params.type,
      traceId: "trace-env",
      spanId: params.spanId || `span-${params.id}`,
      parentSpanId: params.parentSpanId || null,
      executionId: "exec-env",
      timestamp: params.timestamp || new Date().toISOString(),
    },
    input: params.input || {
      data: null,
      type: "wire/json",
      sizeBytes: 128,
      source: "upstream_node",
      classification: "ACTUAL",
    },
    operation: params.operation || {
      name: params.label,
      details: params.sublabel || "Execution step",
      logicMetadata: ["Validated parameters", "Checked invariants"],
      classification: "ACTUAL",
    },
    output: params.output || {
      data: "output_payload",
      type: "wire/json",
      sizeBytes: 256,
      classification: "ACTUAL",
    },
    performance: params.performance || {
      startTime: new Date().toISOString(),
      durationMs: params.durationMs || 10,
      latencyMs: params.durationMs || 10,
      classification: "ACTUAL",
    },
    resources: params.resources || {
      tokensIn: 0,
      tokensOut: 0,
      cachedTokens: 0,
      costEstimatedUsd: 0,
      classification: "CALCULATED",
    },
    debugging: params.debugging || {
      logs: [`[INFO] ${params.label} completed successfully`],
      provenance: "ACTUAL",
    },
  };
}

